/**
 * Where a chart title or legend sits along its side of the chart.
 *
 * | Value    | On the top or bottom side | On the left or right side
 * |----------|---------------------------|---------------------------
 * | `start`  | Left                      | Top
 * | `center` | Center                    | Center
 * | `end`    | Right                     | Bottom
 *
 * @group Charts
 */
export type ChartSideAlign = 'start' | 'center' | 'end';
