// `percent` is ChartEx only, where it's spelled `percentage`.
/**
 * A built-in unit for scaling tick labels. `percent` shows values as percentages, as on a Pareto
 * chart's cumulative axis.
 *
 * @group Charts
 */
export type ChartDisplayUnit =
  'hundreds' |
  'thousands' |
  'tenThousands' |
  'hundredThousands' |
  'millions' |
  'tenMillions' |
  'hundredMillions' |
  'billions' |
  'trillions' |
  'percent';
